/**
 * Opt-in: wrap Claude Code's status line so the five-hour and weekly limits it is handed also land
 * in ~/.herdr/statusline-last.json, where server/statusline.ts reads the numbers the web UI shows.
 * Nothing runs this for you.
 *
 * It adds only its own directory, `herdr-statusline/` in Claude's config directory
 * (CLAUDE_CONFIG_DIR, else ~/.claude), and points `statusLine.command` in that directory's
 * settings.json at the wrapper there. The wrapper runs the command that was set before exactly as
 * Claude ran it (`sh -c`, arguments and all), so the line Claude draws stays the same; where no
 * status line was set it draws none. Only the `statusLine` member of settings.json is edited, in
 * place, so the rest of the file keeps its bytes.
 *
 *   bun scripts/install-statusline-tee.ts            # install (or say it is already installed)
 *   bun scripts/install-statusline-tee.ts --remove   # undo it (`--restore` does the same)
 *
 * `--remove` writes settings.json back byte for byte when nothing else in it changed since the
 * install, and otherwise puts back only the status line it replaced (or its absence). It then
 * deletes the directory it added and the captured payload. Use the same CLAUDE_CONFIG_DIR as for
 * the install.
 */
import { chmodSync, copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join, resolve } from "node:path";

const BANNER = "# Generated by the herdr web UI's status-line installer (scripts/install-statusline-tee.ts); do not edit.";
const KEY = "statusLine";

interface InstallRecord {
  /** settings.json as it was before the install, and as the install wrote it */
  original: string;
  installed: string;
  /** the `statusLine` value's own text before the install; null where there was none */
  statusLine: string | null;
  command: string;
}

const shellQuote = (value: string): string => (/^[\w./:@%+=,-]+$/.test(value) ? value : `'${value.replaceAll("'", `'\\''`)}'`);
const isObject = (value: unknown): value is Record<string, unknown> => typeof value === "object" && value !== null && !Array.isArray(value);

function locations() {
  const configured = process.env["CLAUDE_CONFIG_DIR"]?.trim();
  const configDir = configured ? resolve(configured) : join(homedir(), ".claude");
  const own = join(configDir, "herdr-statusline");
  const tee = join(own, "statusline-tee.sh");
  return {
    settings: join(configDir, "settings.json"),
    own,
    tee,
    capture: join(own, "statusline-capture.ts"),
    record: join(own, "install.json"),
    command: shellQuote(tee),
    payload: join(homedir(), ".herdr", "statusline-last.json"),
  };
}

interface Member { start: number; valueStart: number; valueEnd: number }

/**
 * Where each top-level member of a JSON object text sits, so one member can be swapped or dropped
 * without reformatting the rest. The text must already have passed JSON.parse.
 */
function members(text: string): { found: Map<string, Member>; order: Member[]; close: number } {
  let at = 0;
  const space = () => { while (" \t\r\n".includes(text[at] ?? "x")) at++; };
  const string = (): string => {
    const start = at++;
    while (text[at] !== '"') at += text[at] === "\\" ? 2 : 1;
    at++;
    return JSON.parse(text.slice(start, at)) as string;
  };
  const value = () => {
    if (text[at] === '"') { string(); return; }
    if (text[at] !== "{" && text[at] !== "[") {
      while (at < text.length && !" \t\r\n,}]".includes(text[at]!)) at++;
      return;
    }
    let depth = 0;
    do {
      if (text[at] === '"') { string(); continue; }
      if (text[at] === "{" || text[at] === "[") depth++;
      else if (text[at] === "}" || text[at] === "]") depth--;
      at++;
    } while (depth > 0);
  };
  const found = new Map<string, Member>();
  const order: Member[] = [];
  space();
  at++;
  space();
  while (text[at] !== "}") {
    const start = at;
    const key = string();
    space();
    at++;
    space();
    const valueStart = at;
    value();
    const member = { start, valueStart, valueEnd: at };
    found.set(key, member); // JSON.parse keeps the last of a repeated key, and so does this
    order.push(member);
    space();
    if (text[at] === ",") { at++; space(); }
  }
  return { found, order, close: at };
}

/** `text` with its top-level `statusLine` set to the JSON text `value`, or dropped where it is null. */
function withStatusLine(text: string, value: string | null): string {
  const { found, order, close } = members(text);
  const member = found.get(KEY);
  if (member && value !== null) return text.slice(0, member.valueStart) + value + text.slice(member.valueEnd);
  if (member) {
    const index = order.indexOf(member);
    if (index > 0) return text.slice(0, order[index - 1]!.valueEnd) + text.slice(member.valueEnd);
    const next = order[1];
    return next ? text.slice(0, member.start) + text.slice(next.start) : text.slice(0, text.lastIndexOf("{", member.start) + 1) + text.slice(close);
  }
  if (value === null) return text;
  const last = order.at(-1);
  if (!last) return `${text.slice(0, close).trimEnd()}\n  "${KEY}": ${value}\n${text.slice(close)}`;
  const lineStart = text.lastIndexOf("\n", order[0]!.start) + 1;
  const indent = text.slice(lineStart, order[0]!.start);
  const separator = /^[ \t]*$/.test(indent) && lineStart > 0 ? `\n${indent}` : " ";
  return `${text.slice(0, last.valueEnd)},${separator}"${KEY}": ${value}${text.slice(last.valueEnd)}`;
}

function readSettings(path: string): { text: string; value: Record<string, unknown> } {
  if (!existsSync(path)) throw new Error(`${path} is missing: is Claude Code installed, and is CLAUDE_CONFIG_DIR the one it uses?`);
  const text = readFileSync(path, "utf8");
  const value: unknown = JSON.parse(text);
  if (!isObject(value)) throw new Error(`${path} does not hold a JSON object`);
  return { text, value };
}

function wrapper(previous: string | null, capture: string): string {
  const lines = [
    "#!/bin/sh",
    BANNER,
    "# Keeps the limits Claude Code hands its status line where the herdr web UI reads them",
    "# (~/.herdr/statusline-last.json), then runs the status line that was set before, unchanged.",
    "payload=$(cat)",
    `(umask 077; printf '%s' "$payload" | ${shellQuote(process.execPath)} ${shellQuote(capture)}) 2>/dev/null`,
  ];
  if (previous !== null) lines.push(`printf '%s' "$payload" | sh -c ${shellQuote(previous)}`);
  return `${lines.join("\n")}\n`;
}

function install(): string {
  const where = locations();
  const { text, value } = readSettings(where.settings);
  const current = value[KEY];
  if (isObject(current) && current["command"] === where.command) {
    if (existsSync(where.record)) return `already installed: ${where.settings} runs ${where.command}`;
    throw new Error(`${where.settings} runs ${where.command}, but ${where.record} is gone, so the status line it wrapped is unknown: set statusLine yourself`);
  }
  if (existsSync(where.tee) && !readFileSync(where.tee, "utf8").includes(BANNER)) throw new Error(`${where.own} holds files this installer did not write; move them away first`);

  const previous = isObject(current) && typeof current["command"] === "string" && current["command"].trim() !== "" ? current["command"] : null;
  const member = members(text).found.get(KEY);
  const installed = withStatusLine(text, JSON.stringify({ ...(isObject(current) ? current : {}), type: "command", command: where.command }));
  const record: InstallRecord = { original: text, installed, statusLine: member ? text.slice(member.valueStart, member.valueEnd) : null, command: where.command };

  mkdirSync(where.own, { recursive: true, mode: 0o700 });
  chmodSync(where.own, 0o700);
  copyFileSync(new URL("./statusline-capture.ts", import.meta.url), where.capture);
  chmodSync(where.capture, 0o600);
  writeFileSync(where.tee, wrapper(previous, where.capture), { mode: 0o700 });
  chmodSync(where.tee, 0o700);
  // the record goes first: an install cut short still leaves what --remove needs
  writeFileSync(where.record, `${JSON.stringify(record, null, 2)}\n`, { mode: 0o600 });
  writeFileSync(where.settings, installed);
  return `installed: ${where.settings} runs ${where.command}, which keeps the limits in ~/.herdr/statusline-last.json`
    + (previous === null ? " (no status line was set, so it draws none)" : ` and then runs ${previous}`);
}

function remove(): string {
  const where = locations();
  if (!existsSync(where.record)) return `nothing to remove: ${where.record} is not there`;
  const record = JSON.parse(readFileSync(where.record, "utf8")) as InstallRecord;
  const { text, value } = readSettings(where.settings);
  let outcome: string;
  if (text === record.installed) {
    writeFileSync(where.settings, record.original);
    outcome = `put ${where.settings} back as it was`;
  } else if (isObject(value[KEY]) && value[KEY]["command"] === record.command) {
    writeFileSync(where.settings, withStatusLine(text, record.statusLine));
    outcome = `put back the status line in ${where.settings}; its other changes since the install stay`;
  } else {
    outcome = `left ${where.settings} as it is: its status line was changed since the install`;
  }
  rmSync(where.own, { recursive: true, force: true });
  rmSync(where.payload, { force: true });
  return `removed: ${outcome}, and deleted ${where.own} and ${where.payload}`;
}

function main(argv: readonly string[]): number {
  const unknown = argv.filter((arg) => arg !== "--remove" && arg !== "--restore");
  if (unknown.length > 0) {
    console.error(`unknown argument: ${unknown.join(" ")} (use --remove to undo the install)`);
    return 1;
  }
  if (process.platform === "win32") {
    console.error("the status-line wrapper is a POSIX shell script; Windows is not supported");
    return 1;
  }
  try {
    console.log(argv.length > 0 ? remove() : install());
    return 0;
  } catch (error) {
    console.error(`status-line installer failed: ${error instanceof Error ? error.message : String(error)}`);
    return 1;
  }
}

process.exit(main(process.argv.slice(2)));
